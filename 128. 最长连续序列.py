"""
================================================================================
算法思路
================================================================================

核心思想：
    利用集合（set）的 O(1) 查找特性，只从连续序列的"起点"开始计算长度，
    避免对同一序列重复计算，从而保证 O(n) 时间复杂度。

步骤：
    1. 将数组转为集合 set_nums，实现 O(1) 查找
    2. 遍历集合中的每个数字 num：
       a. 检查 num - 1 是否不在集合中
          - 如果不在：说明 num 是某个连续序列的起点
          - 如果在：跳过，因为 num 不是序列起点，无需计算
       b. 如果 num 是起点，从 num 开始不断向右扩展（num + 1, num + 2, ...）
          直到连续数字不在集合中为止，记录序列长度
       c. 更新最大长度 max_len
    3. 返回 max_len

关键点：为什么是 O(n) 而不是 O(n^2)？
    - 每个数字只会在"作为序列起点"时被扩展一次
    - 例如 [1, 2, 3, 4]，只有遍历到 1 时才会扩展检查 2, 3, 4
    - 遍历到 2 时，因为 2 - 1 = 1 在集合中，跳过
    - 遍历到 3 时，因为 3 - 1 = 2 在集合中，跳过
    - 所以总遍历次数是 n + n（最多扩展 n 次）= O(n)

时间复杂度：O(n)
    遍历集合 O(n)，每个元素最多扩展一次，总体 O(n)

空间复杂度：O(n)
    需要存储 n 个元素到集合中

================================================================================
"""