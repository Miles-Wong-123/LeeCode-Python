from typing import List

class Solution:
    def groupAnagrams(self, strs: List[str]) -> List[List[str]]:
        sorted_strs = {}
        
        for s in strs:
            """
            sort(s)的结果是一个列表, 需要使用join()方法将其转换为字符串,才能作为key
            """
            s1 = ''.join(sorted(s))

            if s1 not in sorted_strs.keys():
                sorted_strs[s1] = []
            sorted_strs[s1].append(s)

        return list(sorted_strs.values())


if __name__ == "__main__":
    solution = Solution()
    strs = ["eat","tea","tan","ate","nat","bat"]
    result = solution.groupAnagrams(strs)
    print(result)


