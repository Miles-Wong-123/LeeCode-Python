from typing import List

class Solution:
    def twoSum(self, nums: List[int], target: int) -> List[int]:
        """
        使用字典一次遍历解决两数之和问题。
        
        核心思想：
        对于数组中的每个元素 nums[i]，我们需要找到 target - nums[i] 是否已经出现过。
        如果出现过，直接返回对应的两个下标；
        如果没出现过，将当前元素的值作为 key，下标作为 value 存入字典。
        """
        seen = {}  # 值 -> 下标

        for i, num in enumerate(nums):
            complement = target - num

            if complement in seen:
                return [seen[complement], i]

            seen[num] = i

        # 理论上不会走到这里，因为题目保证有解
        return []

if __name__ == "__main__":
    # 快速测试
    solution = Solution()

    # 示例 1
    result = solution.twoSum([2, 7, 11, 15], 9)
    print(f"示例 1: {result}")  # 预期 [0, 1]

    # 示例 2
    result = solution.twoSum([3, 2, 4], 6)
    print(f"示例 2: {result}")  # 预期 [1, 2]

    # 示例 3
    result = solution.twoSum([3, 3], 6)
    print(f"示例 3: {result}")  # 预期 [0, 1]

"""
================================================================================
题目：1. 两数之和
================================================================================

给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出 
和为目标值 target  的那两个整数，并返回它们的数组下标。

你可以假设每种输入只会对应一个答案，并且你不能使用两次相同的元素。

你可以按任意顺序返回答案。

示例 1：
    输入：nums = [2,7,11,15], target = 9
    输出：[0,1]
    解释：因为 nums[0] + nums[1] == 9 ，返回 [0, 1] 。

示例 2：
    输入：nums = [3,2,4], target = 6
    输出：[1,2]

示例 3：
    输入：nums = [3,3], target = 6
    输出：[0,1]

提示：
    - 2 <= nums.length <= 10^4
    - -10^9 <= nums[i] <= 10^9
    - -10^9 <= target <= 10^9
    - 只会存在一个有效答案

================================================================================
"""


"""
================================================================================
算法思路说明
================================================================================

【方法一：哈希表法（推荐）】

核心思想：
    利用哈希表（Python 字典）在 O(1) 时间内查找元素的特性，
    将问题从"查找两个数的和"转化为"查找一个数是否存在"。

步骤：
    1. 创建一个空字典 seen，用于存储已遍历过的元素值及其下标
       （key = 元素值, value = 下标）
    2. 遍历数组中每个元素 nums[i]：
       a. 计算 complement = target - nums[i]
          （complement 就是我们需要找到的"另一个数"）
       b. 检查 complement 是否在 seen 字典中：
          - 如果在：说明之前已经遇到过这个数，直接返回 [seen[complement], i]
          - 如果不在：将 nums[i]: i 存入 seen，继续遍历
    3. 遍历结束理论上一定会找到答案（题目保证有解）

时间复杂度：O(n)
    只遍历数组一次，每次查找操作是 O(1)，总体 O(n)

空间复杂度：O(n)
    最坏情况下需要将 n-1 个元素存入字典

为什么只需遍历一次？
    举个例子：nums = [2, 7, 11, 15], target = 9
    - 遍历到 2：complement = 7，seen 中没有 7，存入 seen[2] = 0
    - 遍历到 7：complement = 2，seen 中有 2！返回 [0, 1]
    关键点：当遍历到第二个数时，第一个数已经在字典中了


【方法二：暴力枚举法】

核心思想：
    双重循环，枚举所有可能的两个数的组合，找到和为 target 的那一对。

时间复杂度：O(n^2)
    两层嵌套循环，对于 n 个元素，需要比较 n*(n-1)/2 次

空间复杂度：O(1)
    只使用了常数个变量

优缺点：
    - 优点：思路简单直接，空间复杂度低
    - 缺点：时间复杂度高，对于大规模数据会超时


【两种方法对比】
    ┌──────────────┬─────────────┬─────────────┬──────────────────────┐
    │     方法      │ 时间复杂度   │ 空间复杂度   │      适用场景         │
    ├──────────────┼─────────────┼─────────────┼──────────────────────┤
    │  哈希表法     │    O(n)     │    O(n)     │ 大规模数据，首选方案   │
    │  暴力枚举法   │   O(n^2)    │    O(1)     │ 小规模数据，面试铺垫   │
    └──────────────┴─────────────┴─────────────┴──────────────────────┘

【面试/学习要点】
    1. 哈希表法的关键是将"找两个数"转化为"找一个数"的思想
    2. 注意返回的顺序：先找到的下标在前，后找到的在后
    3. 题目保证唯一解，所以找到即返回，无需考虑重复
    4. Python 中使用 dict 实现哈希表，查找平均 O(1)

================================================================================
"""


