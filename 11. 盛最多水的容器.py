"""
================================================================================
算法思路
================================================================================

核心思想：
    使用双指针法（左右指针）从两端向中间收缩。
    容器面积 = min(height[l], height[r]) * (r - l)
    关键策略：移动较矮的指针，因为容器的高度由较矮的那根柱子决定。

步骤：
    1. 初始化左指针 l = 0（左端），右指针 r = len(height) - 1（右端）
    2. 初始化最大面积 max_area = 0
    3. 当 l < r 时循环：
       a. 计算当前面积：area = min(height[l], height[r]) * (r - l)
       b. 更新最大面积：max_area = max(max_area, area)
       c. 移动指针：
          - 如果 height[l] < height[r]：l += 1（移动较矮的左指针）
          - 否则：r -= 1（移动较矮的右指针）
    4. 返回 max_area

为什么移动较矮的指针？
    - 面积由 min(l, r) 决定，如果移动较高的指针，min 值可能不变，
      但宽度变小了，面积一定减小
    - 移动较矮的指针，min 值有可能变大，从而弥补宽度减小的损失
    - 举个例子：height = [1, 8, 6, 2, 5, 4, 8, 3, 7]
      - l=0(1), r=8(7): 面积 = min(1,7)*8 = 8
      - 应该移动 l（较矮），如果移动 r，面积 = min(1,3)*7 = 7（更小了）
      - 移动 l 到 1(8): 面积 = min(8,7)*7 = 49（更大了）

时间复杂度：O(n)
    只需遍历数组一次，每个指针最多移动 n 步

空间复杂度：O(1)
    只用了常数个变量

================================================================================
"""

