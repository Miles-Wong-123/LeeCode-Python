"""
================================================================================
算法思路
================================================================================

核心思想：
    使用双指针（快慢指针）法，一次遍历即可完成。
    快指针 i 负责遍历数组，慢指针 s 指向最后一个非零元素的下一个位置。

步骤：
    1. 初始化慢指针 s = 0，表示下一个非零元素应该放置的位置
    2. 遍历数组（快指针 i）：
       a. 如果 nums[i] != 0（遇到非零元素）：
          - 将 nums[i] 和 nums[s] 交换
          - s 向前移动一位
       b. 如果 nums[i] == 0（遇到零）：
          - 跳过，继续遍历
    3. 遍历结束后，所有非零元素都在前面，零都在后面

为什么这样做？
    - 慢指针 s 始终指向"下一个非零元素应该放的位置"
    - 遇到非零元素时，交换到 s 的位置，s 前移
    - 遇到零时不移动 s，这样零就自然被"甩"到后面了

示例过程：nums = [0, 1, 0, 3, 12]
    i=0, nums[0]=0: 跳过，s=0
    i=1, nums[1]=1: 交换 nums[0]和nums[1] → [1,0,0,3,12], s=1
    i=2, nums[2]=0: 跳过，s=1
    i=3, nums[3]=3: 交换 nums[1]和nums[3] → [1,3,0,0,12], s=2
    i=4, nums[4]=12: 交换 nums[2]和nums[4] → [1,3,12,0,0], s=3
    结果: [1, 3, 12, 0, 0] ✅

时间复杂度：O(n)
    只需遍历数组一次

空间复杂度：O(1)
    原地操作，只用了常数个变量

================================================================================
"""